/**
 * Downloads public-domain Natural Earth 50m land coastlines, 110m country borders,
 * and 110m major lakes, applies Douglas-Peucker simplification, and outputs a
 * compact self-contained ES module: src/public/world-geo.js.
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'src/public/world-geo.js');

const URLS = {
  land: 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson',
  borders: 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_boundary_lines_land.geojson',
  lakes: 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_lakes.geojson',
};

function perpDist(pt, a, b) {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  if (dx === 0 && dy === 0) return Math.hypot(pt[0] - a[0], pt[1] - a[1]);
  const t = ((pt[0] - a[0]) * dx + (pt[1] - a[1]) * dy) / (dx * dx + dy * dy);
  const clamped = Math.max(0, Math.min(1, t));
  return Math.hypot(pt[0] - (a[0] + clamped * dx), pt[1] - (a[1] + clamped * dy));
}

function simplifyDP(pts, tol) {
  if (pts.length <= 4) return pts;
  let maxD = 0;
  let maxIdx = 0;
  const end = pts.length - 1;
  for (let i = 1; i < end; i++) {
    const d = perpDist(pts[i], pts[0], pts[end]);
    if (d > maxD) {
      maxD = d;
      maxIdx = i;
    }
  }
  if (maxD > tol) {
    const left = simplifyDP(pts.slice(0, maxIdx + 1), tol);
    const right = simplifyDP(pts.slice(maxIdx), tol);
    return left.slice(0, -1).concat(right);
  }
  return [pts[0], pts[end]];
}

function ringAreaApprox(ring) {
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  for (const [x, y] of ring) {
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
  return (maxX - minX) * (maxY - minY);
}

function roundCoords(ring) {
  return ring.map(([lon, lat]) => [
    Math.round(lon * 100) / 100,
    Math.round(lat * 100) / 100,
  ]);
}

function extractPolygons(geojson, tol, minBboxArea) {
  const rings = [];
  for (const feat of geojson.features || []) {
    const g = feat.geometry;
    if (!g) continue;
    const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
    for (const poly of polys) {
      const outer = poly[0];
      if (!outer || outer.length < 4) continue;
      if (ringAreaApprox(outer) < minBboxArea) continue;
      const simplified = simplifyDP(outer, tol);
      if (simplified.length >= 4) {
        rings.push(roundCoords(simplified));
      }
    }
  }
  return rings;
}

function extractLines(geojson, tol) {
  const lines = [];
  for (const feat of geojson.features || []) {
    const g = feat.geometry;
    if (!g) continue;
    const parts = g.type === 'LineString' ? [g.coordinates] : g.type === 'MultiLineString' ? g.coordinates : [];
    for (const line of parts) {
      if (!line || line.length < 2) continue;
      const simplified = simplifyDP(line, tol);
      if (simplified.length >= 2) {
        lines.push(roundCoords(simplified));
      }
    }
  }
  return lines;
}

console.log('[build-world-geo] Downloading Natural Earth 50m/110m public-domain GeoJSON...');
const [landGeo, bordersGeo, lakesGeo] = await Promise.all([
  fetch(URLS.land).then((r) => r.json()),
  fetch(URLS.borders).then((r) => r.json()),
  fetch(URLS.lakes).then((r) => r.json()),
]);

// Keep detailed coastlines (0.08 deg tolerance keeps Korea, Japan, Jeju, Tsushima, Norway fjords, UK, Med crisp!)
const landPolygons = extractPolygons(landGeo, 0.08, 0.04);
const borderLines = extractLines(bordersGeo, 0.14);
const lakePolygons = extractPolygons(lakesGeo, 0.1, 0.25);

const totalLandPts = landPolygons.reduce((a, r) => a + r.length, 0);
const totalBorderPts = borderLines.reduce((a, r) => a + r.length, 0);
const totalLakePts = lakePolygons.reduce((a, r) => a + r.length, 0);

const content = `/**
 * High-resolution Natural Earth 50m coastlines, 110m country borders, and major lakes.
 * Source: Natural Earth (Public Domain). Auto-generated by scripts/build-world-geo.js.
 */

export const WORLD_POLYGONS = ${JSON.stringify(landPolygons)};
export const COUNTRY_BORDERS = ${JSON.stringify(borderLines)};
export const WORLD_LAKES = ${JSON.stringify(lakePolygons)};
`;

await fs.writeFile(outFile, content, 'utf8');
const kb = (Buffer.byteLength(content, 'utf8') / 1024).toFixed(1);
console.log(
  `[build-world-geo] Wrote src/public/world-geo.js (${kb} KB): ` +
    `${landPolygons.length} land rings (${totalLandPts} pts), ` +
    `${borderLines.length} border lines (${totalBorderPts} pts), ` +
    `${lakePolygons.length} lakes (${totalLakePts} pts)`
);
